library(evalsuite)
v <- es_metric("f1", y_true = c(0, 1, 1, 0), y_pred = c(0, 1, 0, 0))
stopifnot(abs(v - 2 / 3) < 1e-15)
r <- es_metric("roc_auc", y_true = c(0, 0, 1, 1, 0, 1), y_prob = c(0.1, 0.4, 0.35, 0.8, 0.2, 0.9), ci = "analytic")
stopifnot(r$ci_method == "delong", r$ci_low <= r$value, r$value <= r$ci_high)
stopifnot("ndcg" %in% es_metrics())
stopifnot(is.infinite(es_metric("lr_positive", y_true = c(0, 1, 1, 0), y_pred = c(0, 1, 1, 0))))
stopifnot(abs(es_metric("mrr", relevant = list("a", "x"), retrieved = list(c("b", "a"), "x")) - 0.75) < 1e-15)
